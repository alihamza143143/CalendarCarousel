export function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(value, max))
}



export const smoothstep = (min: number, max: number, value: number): number => {
  const x = Math.max(0, Math.min(1, (value - min) / (max - min)))
  return x * x * (3 - 2 * x)
}

export const smoothstepLinear = (min: number, max: number, value: number): number => {
  const x = min === max ? 1 : Math.max(0, Math.min(1, (value - min) / (max - min)))
  return x
}

export const getInitialPerspectiveClassName = (index: number, amount: number): string => {
  if (index === 0) return 'center'

  const side = Math.sign(index) === -1 ? 'left' : 'right'
  const evenOrOdd = amount % 2 === 1 ? 'odd' : 'even'

  return `${side}_${Math.abs(index)}_${evenOrOdd}`
}

export const getPerspectiveClassName = (progress: number | undefined): string => {
  if (!progress) return 'center'

  const side = Math.sign(progress) === -1 ? 'left' : 'right'
  const moduleProgress = Math.abs(progress)

  let index = 1
  let evenOrOdd

  if (moduleProgress <= 0.05) {
    return 'center'
  } else if (moduleProgress > 0.05 && moduleProgress <= 0.26) {
    index = 1
    evenOrOdd = 'even'
  } else if (moduleProgress > 0.26 && moduleProgress <= 0.51) {
    index = 1
    evenOrOdd = 'odd'
  } else if (moduleProgress > 0.51 && moduleProgress <= 0.76) {
    index = 2
    evenOrOdd = 'even'
  } else if (moduleProgress > 0.76) {
    index = 2
    evenOrOdd = 'odd'
  }

  return `${side}_${Math.abs(index)}_${evenOrOdd}`
}

const getOddAmountIndex = (index: number, length: number): number => index - (length - 1) / 2
const getEvenAmountIndex = (index: number, length: number): number =>
  index - length / 2 + Math.floor((index * 2) / length)

export const getCabinetIndex = (index: number, length: number): { perspective: number; position: number } => {
  const amount = { max: 2, min: -2 }
  const trueIndex = length % 2 === 1 ? getOddAmountIndex(index, length) : getEvenAmountIndex(index, length)

  return { perspective: clamp(trueIndex, amount.min, amount.max), position: trueIndex }
}

export const roundUpToHalf = (num: number) => {
  return Math.ceil(num * 2) / 2
}

export const roundUpToQuarter = (num: number) => {
  return Math.ceil(num * 4) / 4
}

export const roundDownToQuarter = (num: number) => {
  return Math.floor(num * 4) / 4
}

export const roundToQuarter = (num: number) => {
  return Math.round(num * 4) / 4
}

export const lerp = (x: number, y: number, t: number) => {
  return (1 - t) * x + t * y
}

export const getDt = () => 1.0 - (1.0 - 0.1) ** gsap.ticker.deltaRatio()

export const round = (t: number, i: number) => {
  i = i !== 0 ? 10 ** i : 1e3
  return Math.round(t * i) / i
}


