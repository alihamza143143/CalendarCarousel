export const pxToVmin = (px: number): number => {
  const vmin = Math.min(window.innerWidth, window.innerHeight)
  return (px / vmin) * 100
}

export const getInfinityPosition = (elPosition: number, whole: number, offset: number): number => {
  if (whole === offset) {
    return elPosition
  }

  return (((elPosition % whole) + whole + offset) % whole) - offset
}


